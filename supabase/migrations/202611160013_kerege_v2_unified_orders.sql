-- KEREGE 2.0: unified supplier orders, immutable line snapshots,
-- fulfillment tracking and payment ledger foundation.
-- Existing purchase_requests remain as compatibility records for current chat/history UI.

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  buyer_id uuid not null references public.profiles(id) on delete restrict,
  supplier_id uuid not null references public.supplier_public_profiles(id) on delete restrict,
  status text not null default 'new'
    check (status in ('new','accepted','preparing','ready_for_pickup','shipped','delivered','completed','declined','cancelled')),
  currency text not null default 'KGS' check (currency = 'KGS'),
  subtotal numeric(14,2) not null default 0 check (subtotal >= 0),
  delivery_fee numeric(14,2) not null default 0 check (delivery_fee >= 0),
  total numeric(14,2) not null default 0 check (total >= 0),
  delivery_method text not null check (delivery_method in ('supplier_delivery','pickup')),
  delivery_address text not null default '',
  delivery_note text not null default '',
  recipient_name text not null default '',
  recipient_phone text not null default '',
  buyer_note text not null default '',
  supplier_note text not null default '',
  accepted_at timestamptz,
  shipped_at timestamptz,
  delivered_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (buyer_id <> supplier_id)
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  legacy_request_id uuid unique references public.purchase_requests(id) on delete set null,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  unit text not null,
  quantity numeric(14,3) not null check (quantity > 0),
  unit_price numeric(14,2) not null check (unit_price >= 0),
  line_total numeric(14,2) generated always as (round(quantity * unit_price, 2)) stored,
  created_at timestamptz not null default now()
);

create index if not exists orders_buyer_created_idx on public.orders(buyer_id,created_at desc);
create index if not exists orders_supplier_created_idx on public.orders(supplier_id,created_at desc);
create index if not exists orders_status_created_idx on public.orders(status,created_at desc);
create index if not exists order_items_order_idx on public.order_items(order_id);

create table if not exists public.order_status_events (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  old_status text,
  new_status text not null,
  note text not null default '',
  changed_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists order_status_events_order_idx on public.order_status_events(order_id,created_at asc);

-- Payment ledger is provider-neutral. No payment is captured until a real provider is connected.
create table if not exists public.payment_transactions (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete restrict,
  payer_id uuid not null references public.profiles(id) on delete restrict,
  amount numeric(14,2) not null check (amount > 0),
  currency text not null default 'KGS' check (currency = 'KGS'),
  provider text not null default 'manual' check (provider in ('manual','provider_pending')),
  provider_reference text,
  status text not null default 'pending' check (status in ('pending','authorized','paid','failed','refunded','cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists payment_transactions_order_idx on public.payment_transactions(order_id,created_at desc);

alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.order_status_events enable row level security;
alter table public.payment_transactions enable row level security;

revoke all on public.orders,public.order_items,public.order_status_events,public.payment_transactions from anon,authenticated;
grant select on public.orders,public.order_items,public.order_status_events,public.payment_transactions to authenticated;

drop policy if exists orders_parties_read on public.orders;
create policy orders_parties_read on public.orders for select to authenticated
using (buyer_id=auth.uid() or supplier_id=auth.uid());

drop policy if exists order_items_parties_read on public.order_items;
create policy order_items_parties_read on public.order_items for select to authenticated
using (exists(select 1 from public.orders o where o.id=order_id and (o.buyer_id=auth.uid() or o.supplier_id=auth.uid())));

drop policy if exists order_events_parties_read on public.order_status_events;
create policy order_events_parties_read on public.order_status_events for select to authenticated
using (exists(select 1 from public.orders o where o.id=order_id and (o.buyer_id=auth.uid() or o.supplier_id=auth.uid())));

drop policy if exists payment_parties_read on public.payment_transactions;
create policy payment_parties_read on public.payment_transactions for select to authenticated
using (payer_id=auth.uid() or exists(select 1 from public.orders o where o.id=order_id and o.supplier_id=auth.uid()));

create or replace function public.create_supplier_order(
  p_supplier_id uuid,
  p_items jsonb,
  p_delivery_method text,
  p_delivery_address text default '',
  p_delivery_note text default '',
  p_recipient_name text default '',
  p_recipient_phone text default '',
  p_buyer_note text default ''
)
returns uuid
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_buyer uuid := auth.uid();
  v_order_id uuid;
  v_subtotal numeric(14,2) := 0;
  v_item jsonb;
  v_product public.products%rowtype;
  v_qty numeric(14,3);
  v_request_id uuid;
begin
  if v_buyer is null then raise exception 'Требуется авторизация'; end if;
  if not exists(select 1 from public.profiles where id=v_buyer and role='buyer') then
    raise exception 'Оформлять заказы могут только покупатели';
  end if;
  if p_delivery_method not in ('supplier_delivery','pickup') then
    raise exception 'Выберите способ получения';
  end if;
  if p_items is null or jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)=0 then
    raise exception 'В заказе нет товаров';
  end if;

  for v_item in select value from jsonb_array_elements(p_items) loop
    select * into v_product from public.products
    where id=(v_item->>'product_id')::uuid and supplier_id=p_supplier_id and is_active=true
    for share;
    if not found then raise exception 'Товар недоступен или принадлежит другому поставщику'; end if;
    v_qty := (v_item->>'quantity')::numeric;
    if v_qty is null or v_qty < v_product.min_order then
      raise exception 'Количество ниже минимального заказа для товара: %',v_product.name;
    end if;
    v_subtotal := v_subtotal + round(v_qty*v_product.price,2);
  end loop;

  insert into public.orders(buyer_id,supplier_id,subtotal,total,delivery_method,delivery_address,delivery_note,recipient_name,recipient_phone,buyer_note)
  values(v_buyer,p_supplier_id,v_subtotal,v_subtotal,p_delivery_method,
    coalesce(p_delivery_address,''),coalesce(p_delivery_note,''),coalesce(p_recipient_name,''),coalesce(p_recipient_phone,''),coalesce(p_buyer_note,''))
  returning id into v_order_id;

  for v_item in select value from jsonb_array_elements(p_items) loop
    select * into v_product from public.products
    where id=(v_item->>'product_id')::uuid and supplier_id=p_supplier_id and is_active=true;
    v_qty := (v_item->>'quantity')::numeric;
    insert into public.purchase_requests(buyer_id,supplier_id,product_id,quantity,message,delivery_method,delivery_details)
    values(v_buyer,p_supplier_id,v_product.id,v_qty,'Заказ KEREGE #'||v_order_id::text,p_delivery_method,
      case when p_delivery_method='supplier_delivery' then coalesce(p_delivery_address,'') else coalesce(p_delivery_note,'') end)
    returning id into v_request_id;

    insert into public.order_items(order_id,legacy_request_id,product_id,product_name,unit,quantity,unit_price)
    values(v_order_id,v_request_id,v_product.id,v_product.name,v_product.unit,v_qty,v_product.price);
  end loop;

  insert into public.order_status_events(order_id,old_status,new_status,note,changed_by)
  values(v_order_id,null,'new','Заказ создан покупателем',v_buyer);
  return v_order_id;
end;
$$;

create or replace function public.set_supplier_order_status(p_order_id uuid,p_new_status text,p_note text default '')
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_user uuid := auth.uid();
  v_order public.orders%rowtype;
  v_allowed boolean := false;
begin
  if v_user is null then raise exception 'Требуется авторизация'; end if;
  if not exists(select 1 from public.profiles where id=v_user and role='supplier') then
    raise exception 'Доступ разрешён только поставщику';
  end if;
  select * into v_order from public.orders where id=p_order_id and supplier_id=v_user for update;
  if not found then raise exception 'Заказ не найден'; end if;

  v_allowed := (v_order.status='new' and p_new_status in ('accepted','declined'))
    or (v_order.status='accepted' and p_new_status in ('preparing','ready_for_pickup','shipped'))
    or (v_order.status='preparing' and p_new_status in ('ready_for_pickup','shipped'))
    or (v_order.status='ready_for_pickup' and p_new_status='completed')
    or (v_order.status='shipped' and p_new_status='delivered')
    or (v_order.status='delivered' and p_new_status='completed');
  if not v_allowed then raise exception 'Недопустимый переход статуса: % → %',v_order.status,p_new_status; end if;

  update public.orders set status=p_new_status,updated_at=now(),
    accepted_at=case when p_new_status='accepted' then now() else accepted_at end,
    shipped_at=case when p_new_status='shipped' then now() else shipped_at end,
    delivered_at=case when p_new_status='delivered' then now() else delivered_at end,
    completed_at=case when p_new_status='completed' then now() else completed_at end
  where id=p_order_id;

  insert into public.order_status_events(order_id,old_status,new_status,note,changed_by)
  values(p_order_id,v_order.status,p_new_status,coalesce(p_note,''),v_user);

  update public.purchase_requests set status=
    case p_new_status when 'accepted' then 'accepted' when 'declined' then 'declined'
      when 'completed' then 'completed' else status end
  where id in (select legacy_request_id from public.order_items where order_id=p_order_id and legacy_request_id is not null)
    and (p_new_status in ('accepted','declined','completed'));
end;
$$;

revoke all on function public.create_supplier_order(uuid,jsonb,text,text,text,text,text,text) from public,anon;
revoke all on function public.set_supplier_order_status(uuid,text,text) from public,anon;
grant execute on function public.create_supplier_order(uuid,jsonb,text,text,text,text,text,text) to authenticated;
grant execute on function public.set_supplier_order_status(uuid,text,text) to authenticated;

-- Prevent direct client writes to order and payment ledgers; all writes go through validated RPCs.
revoke insert,update,delete on public.orders,public.order_items,public.order_status_events,public.payment_transactions from anon,authenticated;
